  function edwiseSetLanguage(lang) {

    const selected = ["tr","en","ar"].includes(lang) ? lang : "tr";

    const dict = EDWISE_I18N[selected] || {};

    edwiseTextNodes.forEach(({node,raw,key}) => {

      if (selected === "tr") node.nodeValue = raw;

      else if (Object.prototype.hasOwnProperty.call(dict,key)) {

        const leading = raw.match(/^\s*/)[0];

        const trailing = raw.match(/\s*$/)[0];

        node.nodeValue = leading + dict[key] + trailing;

      } else node.nodeValue = raw;

    });

    if (edwiseH1) {

      edwiseH1.innerHTML = selected === "tr" ? edwiseH1Original : edwiseH1Translations[selected];

    }

    document.documentElement.lang = selected;

    document.documentElement.dir = selected === "ar" ? "rtl" : "ltr";

    document.body.dir = selected === "ar" ? "rtl" : "ltr";

    document.querySelectorAll(".lang-btn").forEach(button => {

      const active = button.dataset.lang === selected;

      button.classList.toggle("active", active);

      button.setAttribute("aria-pressed", active ? "true" : "false");

      button.setAttribute("aria-pressed", active ? "true" : "false");

    });

    try { localStorage.setItem("edwise-language", selected); } catch(error) {}

  }



  document.querySelectorAll(".lang-btn").forEach(button => {

    button.addEventListener("click", () => edwiseSetLanguage(button.dataset.lang));

  });

  let initialLanguage = "tr";

  try { initialLanguage = localStorage.getItem("edwise-language") || "tr"; } catch(error) {}

  edwiseSetLanguage(initialLanguage);



